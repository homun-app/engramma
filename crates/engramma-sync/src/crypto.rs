//! The sealed operations (v0.6, P4). A cell shared across devices travels
//! in ENVELOPES: XChaCha20-Poly1305 under a per-EPOCH cell key, the key
//! wrapped for each device with HPKE (RFC 9180, base mode, X25519
//! HKDF-SHA256, ChaCha20-Poly1305). The relay and the blind mailbox see
//! ciphertext, sizes and timing — nothing else.
//!
//! The ids the mailbox indexes are OPAQUE: `cell_sync_id` is an HMAC of
//! the epoch-0 key, and an operation's opaque id is an HMAC of the
//! content_hash under a MAC key derived from epoch 0 — stable across
//! epochs, so operations recognize each other while the mailbox cannot
//! read an `op_id` or an HLC.
//!
//! What this phase does NOT promise: neither post-compromise security nor
//! forward secrecy per message. A stolen epoch key opens the whole epoch;
//! the rotation at a `remove` is the compromise chosen for one owner's
//! devices (DESIGN § 10, with the alternatives and why they wait: MLS
//! wants a delivery service that orders, BeeKEM/Keyhive and DCGKA are
//! pre-alpha today).

use chacha20poly1305::XChaCha20Poly1305 as XCipher;
use chacha20poly1305::aead::{Aead, KeyInit, Payload};
use hkdf::Hkdf;
use sha2::Sha256;

use crate::{Error, Result};

/// The label of the epoch-key → operation-key derivation.
const LABEL_OP_KEY: &[u8] = b"engramma/op/v1";
/// The label of the cell id HMAC.
const LABEL_CELL_ID: &[u8] = b"engramma/cell-id/v1";
/// The label of the epoch-0 → MAC-key derivation.
const LABEL_MAC_KEY: &[u8] = b"engramma/opaque-id/v1";
/// The HPKE info prefix.
const LABEL_CELLKEY: &[u8] = b"engramma/cellkey/v1";

/// One cell's key for one epoch: 32 random bytes, generated by whoever
/// opens the epoch (the sharer at 0, the remover at k+1).
#[derive(Clone)]
pub struct EpochKey(pub [u8; 32]);

impl EpochKey {
    /// A fresh, random epoch key.
    ///
    /// # Errors
    /// [`Error::Io`] when the system CSPRNG fails.
    pub fn generate() -> Result<Self> {
        let mut k = [0_u8; 32];
        getrandom::fill(&mut k).map_err(std::io::Error::other)?;
        Ok(Self(k))
    }

    /// The cell's opaque sync id: HMAC-SHA256 of the EPOCH-0 key — stable
    /// for the cell's whole life, known only to key holders.
    #[must_use]
    pub fn cell_sync_id(&self) -> [u8; 32] {
        hmac(&self.0, LABEL_CELL_ID, b"")
    }

    /// The MAC key: derived from the epoch-0 key once, stable across
    /// epochs so operation ids recognize each other while nothing else
    /// about them is public.
    #[must_use]
    pub fn mac_key(&self) -> [u8; 32] {
        hmac(&self.0, LABEL_MAC_KEY, b"")
    }

    /// The operation-sealing key of this epoch: HKDF of the epoch key.
    #[must_use]
    pub fn op_key(&self) -> [u8; 32] {
        hkdf_32(&self.0, LABEL_OP_KEY, &[])
    }

    /// The opaque id of an operation: HMAC of its content_hash under the
    /// stable MAC key.
    #[must_use]
    pub fn opaque_op_id(mac_key: &[u8; 32], content_hash: &[u8]) -> [u8; 32] {
        hmac(mac_key, b"engramma/op-id/v1", content_hash)
    }
}

/// A sealed operation: the nonce and the ciphertext. The AAD travels in
/// the clear — it is the routing the mailbox needs (`cell_sync_id ‖ epoch
/// ‖ opaque id`), and it is exactly what an attacker cannot change without
/// the seal breaking.
#[derive(Debug, Clone)]
pub struct Envelope {
    /// The random 24-byte XChaCha nonce. Never reused under the same key.
    pub nonce: [u8; 24],
    /// The ciphertext (and Poly1305 tag appended).
    pub ct: Vec<u8>,
}

/// Seal one operation for an epoch.
///
/// # Errors
/// [`Error::Io`] when the system CSPRNG fails.
pub fn seal_op(key: &EpochKey, aad: &[u8], plaintext: &[u8]) -> Result<Envelope> {
    let mut nonce = [0_u8; 24];
    getrandom::fill(&mut nonce).map_err(std::io::Error::other)?;
    let op_key = key.op_key();
    let cipher = XCipher::new((&op_key).into());
    let ct = cipher
        .encrypt(
            &nonce.into(),
            Payload {
                msg: plaintext,
                aad,
            },
        )
        .map_err(|_| Error::Malformed("seal failed".into()))?;
    Ok(Envelope { nonce, ct })
}

/// Open one operation. A wrong key, a wrong epoch, a tampered byte or a
/// mismatched AAD all fail here — the seal is the whole story.
///
/// # Errors
/// [`Error::Malformed`] when the envelope does not open.
pub fn open_op(key: &EpochKey, aad: &[u8], envelope: &Envelope) -> Result<Vec<u8>> {
    let op_key = key.op_key();
    let cipher = XCipher::new((&op_key).into());
    cipher
        .decrypt(
            &envelope.nonce.into(),
            Payload {
                msg: &envelope.ct,
                aad,
            },
        )
        .map_err(|_| Error::Malformed("the envelope does not open".into()))
}

/// Wrap one epoch key for one device (HPKE, RFC 9180 base mode:
/// X25519 HKDF-SHA256, ChaCha20-Poly1305).
///
/// # Errors
/// [`Error::Io`] on CSPRNG failure, [`Error::Malformed`] on HPKE failure.
pub fn wrap_key(
    key: &EpochKey,
    cell_sync_id: &[u8; 32],
    epoch: u64,
    device_hpke_public: &[u8; 32],
) -> Result<Vec<u8>> {
    use hpke::aead::ChaCha20Poly1305;
    use hpke::kem::X25519HkdfSha256;
    use hpke::{Deserializable, Kem, OpModeS, Serializable, setup_sender};
    let mut info = LABEL_CELLKEY.to_vec();
    info.extend_from_slice(cell_sync_id);
    info.extend_from_slice(&epoch.to_be_bytes());
    let pk_recipient = <X25519HkdfSha256 as Kem>::PublicKey::from_bytes(device_hpke_public)
        .map_err(|_| Error::Malformed("bad hpke public key".into()))?;
    let (encapsulated, mut seal_ctx) = setup_sender::<
        ChaCha20Poly1305,
        hpke::kdf::HkdfSha256,
        X25519HkdfSha256,
    >(&OpModeS::Base, &pk_recipient, &info)
    .map_err(|_| Error::Malformed("hpke setup failed".into()))?;
    let ct = seal_ctx
        .seal(&key.0, b"")
        .map_err(|_| Error::Malformed("hpke seal failed".into()))?;
    let mut out = encapsulated.to_bytes().to_vec();
    out.extend_from_slice(&ct);
    Ok(out)
}

/// Unwrap an epoch key with a device's HPKE secret.
///
/// # Errors
/// [`Error::Malformed`] when the wrap does not open.
pub fn unwrap_key(
    wrapped: &[u8],
    cell_sync_id: &[u8; 32],
    epoch: u64,
    device_hpke_secret: &[u8; 32],
) -> Result<EpochKey> {
    use hpke::aead::ChaCha20Poly1305;
    use hpke::kem::X25519HkdfSha256;
    use hpke::{Deserializable, Kem, OpModeR, setup_receiver};
    if wrapped.len() < 32 {
        return Err(Error::Malformed("wrap too short".into()));
    }
    let (enc, ct) = wrapped.split_at(32);
    let mut info = LABEL_CELLKEY.to_vec();
    info.extend_from_slice(cell_sync_id);
    info.extend_from_slice(&epoch.to_be_bytes());
    let sk = <X25519HkdfSha256 as Kem>::PrivateKey::from_bytes(device_hpke_secret)
        .map_err(|_| Error::Malformed("bad hpke secret".into()))?;
    let encapsulated = <X25519HkdfSha256 as Kem>::EncappedKey::from_bytes(enc)
        .map_err(|_| Error::Malformed("bad encapsulated key".into()))?;
    let mut open_ctx = setup_receiver::<ChaCha20Poly1305, hpke::kdf::HkdfSha256, X25519HkdfSha256>(
        &OpModeR::Base,
        &sk,
        &encapsulated,
        &info,
    )
    .map_err(|_| Error::Malformed("hpke setup failed".into()))?;
    let pt = open_ctx
        .open(ct, b"")
        .map_err(|_| Error::Malformed("the wrap does not open".into()))?;
    let mut k = [0_u8; 32];
    if pt.len() != 32 {
        return Err(Error::Malformed("wrapped key must be 32 bytes".into()));
    }
    k.copy_from_slice(&pt);
    Ok(EpochKey(k))
}

fn hkdf_32(ikm: &[u8], info: &[u8], salt: &[u8]) -> [u8; 32] {
    let hk = Hkdf::<Sha256>::new(Some(salt), ikm);
    let mut okm = [0_u8; 32];
    hk.expand(info, &mut okm)
        .expect(/* fixed sizes */ "expand cannot fail");
    okm
}

fn hmac(key: &[u8], label: &[u8], msg: &[u8]) -> [u8; 32] {
    // HKDF in extract-then-expand mode is the HMAC here (RFC 5869's
    // extract IS HMAC-SHA256)
    let hk = Hkdf::<Sha256>::new(Some(key), msg);
    let mut out = [0_u8; 32];
    hk.expand(label, &mut out)
        .expect(/* fixed sizes */ "expand cannot fail");
    out
}
